"""Agent tools for composing, previewing, and sending authenticated emails."""

from __future__ import annotations

from typing import TYPE_CHECKING

from pydantic import BaseModel, Field

from core.permissions import PermissionCategory
from core.tool_proposal import RiskLevel, ToolDefinition
from tools.base import BaseTool, ToolResult
from tools.communication.email.email_service import get_email_service

if TYPE_CHECKING:
    from core.execution_context import ExecutionContext


class EmailComposeInput(BaseModel):
    to: list[str] = Field(description="List of destination email addresses")
    subject: str = Field(description="Subject line of the email")
    body_text: str = Field(description="Plain text content of the email message")
    body_html: str | None = Field(default=None, description="Optional HTML formatted body")
    cc: list[str] | None = Field(default=None, description="Optional CC recipient email addresses")
    bcc: list[str] | None = Field(
        default=None, description="Optional BCC recipient email addresses"
    )
    attachment_paths: list[str] | None = Field(
        default=None, description="List of local canonical file paths to attach"
    )
    provider: str | None = Field(
        default=None, description="Email provider to use: 'gmail' or 'msgraph'"
    )


class EmailSendInput(BaseModel):
    draft_id: str | None = Field(default=None, description="Draft ID generated by email_compose")
    payload_hash: str | None = Field(
        default=None, description="Cryptographic SHA256 digest of approved draft payload"
    )
    proposal_id: str | None = Field(default=None, description="Unique tool proposal approval ID")
    to: list[str] | None = Field(
        default=None, description="Direct recipients if sending without prior compose"
    )
    subject: str | None = Field(
        default=None, description="Subject line if sending without prior compose"
    )
    body_text: str | None = Field(
        default=None, description="Message body if sending without prior compose"
    )
    attachment_paths: list[str] | None = Field(
        default=None, description="Attachments if sending directly"
    )
    provider: str | None = Field(default=None, description="Target email provider")


class EmailStatusInput(BaseModel):
    pass


class EmailComposeTool(BaseTool):
    """Tool to compose, validate, and prepare an email draft with security checks."""

    name = "email_compose"
    description = (
        "Compose and validate an email draft, validating recipients and attachments. "
        "Returns a draft preview before the user is asked for send approval."
    )
    category = PermissionCategory.EMAIL_COMPOSE
    input_schema = EmailComposeInput

    def execute(self, params: BaseModel, context: ExecutionContext) -> ToolResult:
        p = (
            params
            if isinstance(params, EmailComposeInput)
            else EmailComposeInput.model_validate(
                params if isinstance(params, dict) else params.model_dump()
            )
        )
        service = get_email_service()

        try:
            msg = service.compose_draft(
                to=p.to,
                subject=p.subject,
                body_text=p.body_text,
                body_html=p.body_html,
                cc=p.cc,
                bcc=p.bcc,
                attachment_paths=p.attachment_paths,
                provider=p.provider,
            )
            return ToolResult.success(
                data={
                    "draft_id": msg.draft_id,
                    "preview": msg.to_preview_dict(),
                    "status": "draft_created",
                },
                message=f"Draft '{msg.draft_id}' prepared for {msg.to}. Ready for user approval.",
            )
        except Exception as exc:
            return ToolResult.failed(f"Failed to compose email: {exc}")

    @classmethod
    def get_definition(cls) -> ToolDefinition:
        return ToolDefinition(
            name=cls.name,
            description=cls.description,
            category=cls.category,
            risk_level=RiskLevel.LOW,
            parameters_schema={
                "type": "object",
                "properties": {
                    "to": {"type": "array", "items": {"type": "string"}},
                    "subject": {"type": "string"},
                    "body_text": {"type": "string"},
                    "attachment_paths": {"type": "array", "items": {"type": "string"}},
                    "provider": {"type": "string"},
                },
                "required": ["to", "subject", "body_text"],
            },
            requires_approval=False,
            timeout_seconds=10.0,
        )


class EmailSendTool(BaseTool):
    """Tool to send an email through an authenticated email provider. REQUIRES APPROVAL."""

    name = "email_send"
    description = (
        "Send an email through an authenticated provider (Gmail or Microsoft Graph). "
        "REQUIRES EXPLICIT USER APPROVAL with complete preview before dispatch."
    )
    category = PermissionCategory.EMAIL_SEND
    input_schema = EmailSendInput

    def execute(self, params: BaseModel, context: ExecutionContext) -> ToolResult:
        if context.is_cancelled():
            return ToolResult.cancelled("Email sending cancelled by user.")

        p = (
            params
            if isinstance(params, EmailSendInput)
            else EmailSendInput.model_validate(
                params if isinstance(params, dict) else params.model_dump()
            )
        )
        service = get_email_service()

        # If direct sending without prior compose, compose draft first
        draft_id = p.draft_id
        if not draft_id:
            if not p.to or not p.subject or not p.body_text:
                return ToolResult.failed(
                    "Missing required parameters: 'to', 'subject', and 'body_text'."
                )
            try:
                msg = service.compose_draft(
                    to=p.to,
                    subject=p.subject,
                    body_text=p.body_text,
                    attachment_paths=p.attachment_paths,
                    provider=p.provider,
                )
                draft_id = msg.draft_id
            except Exception as exc:
                return ToolResult.failed(f"Email validation failed: {exc}")
        else:
            msg = service.get_draft(draft_id)
            if not msg:
                return ToolResult.failed(f"Email draft '{draft_id}' not found.")
            actual_hash = msg.compute_payload_hash()
            if p.payload_hash and actual_hash != p.payload_hash:
                return ToolResult.failed(
                    "Payload tampering detected: email draft contents modified after approval request."
                )

            from core.approval import TrustedApprovalStore

            approval_store = TrustedApprovalStore.get_instance()
            target_account = p.provider or msg.provider
            target_recip = ",".join(sorted(msg.to))
            check_key = p.payload_hash or actual_hash
            if approval_store.has_approval(check_key) or p.proposal_id:
                ok, err = approval_store.verify_and_consume(
                    tool_name="email_send",
                    account_id=target_account,
                    recipient=target_recip,
                    actual_payload_hash=actual_hash,
                    proposal_id=p.proposal_id,
                )
                if not ok:
                    return ToolResult.failed(f"Approval integrity verification failed: {err}")

        result = service.send_draft(draft_id)
        if result.success:
            return ToolResult.success(
                data={
                    "status": result.status.value,
                    "message_id": result.message_id,
                    "provider": result.provider,
                    "timestamp": result.timestamp.isoformat(),
                },
                message=f"Email successfully sent via {result.provider} (ID: {result.message_id}).",
            )

        return ToolResult.failed(
            f"Failed to send email via {result.provider}: {result.error}",
            data={"status": result.status.value, "error": result.error},
        )

    @classmethod
    def get_definition(cls) -> ToolDefinition:
        return ToolDefinition(
            name=cls.name,
            description=cls.description,
            category=cls.category,
            risk_level=RiskLevel.HIGH,
            parameters_schema={
                "type": "object",
                "properties": {
                    "draft_id": {"type": "string"},
                    "to": {"type": "array", "items": {"type": "string"}},
                    "subject": {"type": "string"},
                    "body_text": {"type": "string"},
                    "provider": {"type": "string"},
                },
            },
            requires_approval=True,
            timeout_seconds=30.0,
        )


class EmailStatusTool(BaseTool):
    """Tool to inspect connected email account statuses."""

    name = "email_status"
    description = (
        "Check authentication status of configured email providers (Gmail, Microsoft Graph)."
    )
    category = PermissionCategory.EMAIL_COMPOSE
    input_schema = EmailStatusInput

    def execute(self, params: BaseModel, context: ExecutionContext) -> ToolResult:
        service = get_email_service()
        data = service.get_accounts_status()
        return ToolResult.success(data=data, message="Email accounts status retrieved.")

    @classmethod
    def get_definition(cls) -> ToolDefinition:
        return ToolDefinition(
            name=cls.name,
            description=cls.description,
            category=cls.category,
            risk_level=RiskLevel.LOW,
            parameters_schema={"type": "object", "properties": {}},
            requires_approval=False,
            timeout_seconds=5.0,
        )
