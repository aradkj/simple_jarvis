"""Agent tools for composing, previewing, and sending official WhatsApp Cloud API messages."""

from __future__ import annotations

from typing import TYPE_CHECKING

from pydantic import BaseModel, Field

from core.permissions import PermissionCategory
from core.tool_proposal import RiskLevel, ToolDefinition
from tools.base import BaseTool, ToolResult
from tools.communication.whatsapp.whatsapp_service import get_whatsapp_service

if TYPE_CHECKING:
    from core.execution_context import ExecutionContext


class WhatsAppComposeInput(BaseModel):
    recipient: str = Field(description="Destination phone number (E.164) or 'خودم'/'myself'")
    message_text: str = Field(description="Text message content to send via WhatsApp")
    recipient_name: str | None = Field(
        default=None, description="Optional contact name for preview"
    )
    template_name: str | None = Field(
        default=None, description="Optional approved Meta template name"
    )


class WhatsAppSendInput(BaseModel):
    draft_id: str | None = Field(default=None, description="Draft ID generated by whatsapp_compose")
    payload_hash: str | None = Field(
        default=None, description="Cryptographic SHA256 digest of approved draft payload"
    )
    proposal_id: str | None = Field(default=None, description="Unique tool proposal approval ID")
    account_id: str | None = Field(
        default=None, description="Optional sending account/phone-number ID"
    )
    recipient: str | None = Field(
        default=None, description="Destination phone number if sending directly"
    )
    message_text: str | None = Field(default=None, description="Message text if sending directly")
    template_name: str | None = Field(default=None, description="Optional template name")


class WhatsAppStatusInput(BaseModel):
    pass


class WhatsAppComposeTool(BaseTool):
    """Tool to compose and validate a WhatsApp message draft. Returns a preview."""

    name = "whatsapp_compose"
    description = (
        "Compose and validate an outbound WhatsApp message. Resolves 'خودم' to configured phone, "
        "normalizes numbers to E.164, and returns a preview ready for user approval."
    )
    category = PermissionCategory.WHATSAPP_COMPOSE
    input_schema = WhatsAppComposeInput

    def execute(self, params: BaseModel, context: ExecutionContext) -> ToolResult:
        p = (
            params
            if isinstance(params, WhatsAppComposeInput)
            else WhatsAppComposeInput.model_validate(
                params if isinstance(params, dict) else params.model_dump()
            )
        )
        service = get_whatsapp_service()

        try:
            msg = service.compose_draft(
                recipient=p.recipient,
                message_text=p.message_text,
                recipient_name=p.recipient_name,
                template_name=p.template_name,
            )
            return ToolResult.success(
                data={
                    "draft_id": msg.draft_id,
                    "preview": msg.to_preview_dict(),
                    "status": "draft_created",
                },
                message=f"WhatsApp draft '{msg.draft_id}' prepared for {msg.recipient_phone}.",
            )
        except Exception as exc:
            return ToolResult.failed(f"Failed to compose WhatsApp message: {exc}")

    @classmethod
    def get_definition(cls) -> ToolDefinition:
        return ToolDefinition(
            name=cls.name,
            description=cls.description,
            category=cls.category,
            risk_level=RiskLevel.LOW,
            parameters_schema={
                "type": "object",
                "properties": {
                    "recipient": {"type": "string", "description": "Phone number or 'خودم'"},
                    "message_text": {"type": "string", "description": "Message content"},
                    "recipient_name": {"type": "string"},
                },
                "required": ["recipient", "message_text"],
            },
            requires_approval=False,
            timeout_seconds=10.0,
        )


class WhatsAppSendTool(BaseTool):
    """Tool to send an outbound WhatsApp message via Meta Cloud API. REQUIRES APPROVAL."""

    name = "whatsapp_send"
    description = (
        "Send a WhatsApp message via Meta WhatsApp Cloud API. "
        "REQUIRES EXPLICIT USER APPROVAL with complete preview before dispatch."
    )
    category = PermissionCategory.WHATSAPP_SEND
    input_schema = WhatsAppSendInput

    def execute(self, params: BaseModel, context: ExecutionContext) -> ToolResult:
        if context.is_cancelled():
            return ToolResult.cancelled("WhatsApp message sending cancelled by user.")

        p = (
            params
            if isinstance(params, WhatsAppSendInput)
            else WhatsAppSendInput.model_validate(
                params if isinstance(params, dict) else params.model_dump()
            )
        )
        service = get_whatsapp_service()

        draft_id = p.draft_id
        if not draft_id:
            if not p.recipient or not p.message_text:
                return ToolResult.failed(
                    "Missing required parameters: 'recipient' and 'message_text'."
                )
            try:
                msg = service.compose_draft(
                    recipient=p.recipient,
                    message_text=p.message_text,
                    template_name=p.template_name,
                )
                draft_id = msg.draft_id
            except Exception as exc:
                return ToolResult.failed(f"WhatsApp validation failed: {exc}")
        else:
            msg = service.get_draft(draft_id)
            if not msg:
                return ToolResult.failed(f"WhatsApp draft '{draft_id}' not found.")
            actual_hash = msg.compute_payload_hash()
            if p.payload_hash and actual_hash != p.payload_hash:
                return ToolResult.failed(
                    "Payload tampering detected: WhatsApp draft contents modified after approval request."
                )

            from core.approval import TrustedApprovalStore

            approval_store = TrustedApprovalStore.get_instance()
            target_account = p.account_id or msg.account_id
            check_key = p.payload_hash or actual_hash
            if approval_store.has_approval(check_key) or p.proposal_id:
                ok, err = approval_store.verify_and_consume(
                    tool_name="whatsapp_send",
                    account_id=target_account,
                    recipient=msg.recipient_phone,
                    actual_payload_hash=actual_hash,
                    proposal_id=p.proposal_id,
                )
                if not ok:
                    return ToolResult.failed(f"Approval integrity verification failed: {err}")

        result = service.send_draft(draft_id)
        if result.success:
            return ToolResult.success(
                data={
                    "status": result.status.value,
                    "message_id": result.message_id,
                    "recipient_phone": result.recipient_phone,
                    "timestamp": result.timestamp.isoformat(),
                },
                message=f"WhatsApp message successfully accepted for {result.recipient_phone} (ID: {result.message_id}).",
            )

        return ToolResult.failed(
            f"Failed to send WhatsApp message: {result.error}",
            data={"status": result.status.value, "error": result.error},
        )

    @classmethod
    def get_definition(cls) -> ToolDefinition:
        return ToolDefinition(
            name=cls.name,
            description=cls.description,
            category=cls.category,
            risk_level=RiskLevel.HIGH,
            parameters_schema={
                "type": "object",
                "properties": {
                    "draft_id": {"type": "string"},
                    "recipient": {"type": "string"},
                    "message_text": {"type": "string"},
                },
            },
            requires_approval=True,
            timeout_seconds=25.0,
        )


class WhatsAppStatusTool(BaseTool):
    """Tool to check WhatsApp Cloud API configuration and readiness."""

    name = "whatsapp_status"
    description = "Check Meta WhatsApp Cloud API configuration, phone number ID, and readiness."
    category = PermissionCategory.WHATSAPP_COMPOSE
    input_schema = WhatsAppStatusInput

    def execute(self, params: BaseModel, context: ExecutionContext) -> ToolResult:
        service = get_whatsapp_service()
        data = service.get_status()
        return ToolResult.success(data=data, message="WhatsApp status retrieved.")

    @classmethod
    def get_definition(cls) -> ToolDefinition:
        return ToolDefinition(
            name=cls.name,
            description=cls.description,
            category=cls.category,
            risk_level=RiskLevel.LOW,
            parameters_schema={"type": "object", "properties": {}},
            requires_approval=False,
            timeout_seconds=5.0,
        )
